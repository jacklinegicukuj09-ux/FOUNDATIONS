// Data types they are used to store data, in javascript, we have two types of data types.
// The most common data types in javascript are:
// 1. String: A string is a sequence of characters. It is used to represent text. Strings are enclosed in single or double quotes.
// 2. Number: A number is a numeric value. It can be an integer or a floating-point number. 
// 3. Boolean: A boolean is a data type that can have one of two values: true or false. It is used to represent logical values.
// 4. Null: Null is a special value that represents the absence of a value or a non-existent object.
// 5. Undefined: Undefined is a special value that represents a variable that has not been assigned a value.
// 6. Object: An object is a collection of key-value pairs. It is used to represent complex data structures.
// 7. Array: An array is a collection of values. It is used to represent a list of items. Arrays are enclosed in square brackets and can contain values of different data types.
// 8. Symbol: A symbol is a unique and immutable data type that is used to represent unique identifiers. It is often used as a key for object properties.
// 9. BigInt: A BigInt is a numeric data type that can represent integers with arbitrary precision. It is used to represent large integers that cannot be represented by the Number data type.
// 10. Function: A function is a block of code that can be executed when called. It is used to perform a specific task or calculation.
// 11. Date: A date is a data type that represents a specific point in time. It is used to represent dates and times.
// 12. RegExp: A regular expression is a pattern that is used to match character combinations in strings. It is used for pattern matching and text manipulation.
// 13. Error: An error is a data type that represents an error that occurred during the execution of a program. It is used to handle exceptions and errors in code.
// 14. Map: A map is a collection of key-value pairs that can be iterated in the order of insertion. It is used to represent a collection of unique keys and their associated values.

